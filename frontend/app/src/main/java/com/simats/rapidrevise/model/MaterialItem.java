package com.simats.rapidrevise.model;

public class MaterialItem {

    private int id;
    private String name;
    private String type;
    private String url;
    private String file;
    private String content;

    public String getContent() {
        return content;
    }

    public int getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getType() {
        return type;
    }

    public String getUrl() {
        return url;
    }

    public String getFile() {
        return file;
    }
}